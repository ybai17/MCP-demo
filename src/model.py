# Because we don't have access to an external LLM API, I am simulating the response generation with placeholder text
# This should mimic the type of formatted JSON tool-call responses the LLM would be providing.

# reference: https://modelcontextprotocol.io/docs/2026-07-28/develop/build-client

import json

CONTENT_NUM_LIMIT = 1
DEBUG_FLAG = True

class Response:
    def __init__(self, content: list[Content]):
        self.content = content

    def to_dict(self):
        return {
            "content": [c.to_dict() for c in self.content]
        }
    
class Content:
    def __init__(self, name: str, input: dict, type: str="text", text: str="", id: int=0):
        self.name = name   # the name of the tool being used, if any
        self.input = input # the input(s) provided to the tool as tool/function call arguments

        # name must be a string
        # input must be a dictionary containing the expected tool call arguments (see mcp_client_test.py line 24)

        self.type = type   # the type of content returned by the LLM, e.g., "text" or "tool_use."" 
        self.text = text   # the textual content or JSON representation of the tool call result
        self.id = id

    def to_dict(self):
        return {
            "name": self.name,
            "input": self.input,
            "type": self.type,
            "text": self.text,
            "id": self.id
        }

