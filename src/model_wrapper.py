from model import Model, Response
import model

DEBUG_FLAG = True

class ModelWrapper:
    """A class to wrap a generic LLM, handling user prompts and responses.

    Attributes:
        name (str): The name of the LLM.
        transport (str): The transport mechanism used for the user to communicate with the LLM (e.g. stdio, http)

    Methods:
        __init__(self, name, transport): Initializes the wrapper instance with the given LLM name and transport.
        send_prompt(self, query): Takes in the user query and sends it to the model
        get_response(self): Returns the last response generated by the model.
    """

    def __init__(self, model: Model, transport: str="stdio"):
        """
        Initializes the wrapper instance with the given LLM name and transport.

        Args:
            model (Model): A Model-type object representing the LLM to be wrapped.
            transport (str): The transport mechanism used for the user to communicate with the LLM. Default is "stdio".
        """
        self.model = model
        self.transport = transport

    def send_prompt(self, model: Model, max_tokens: int=1000, messages: list[dict]=[{}], tools: list[dict]=[]) -> Response:
        """
        Accepts a user query and sends it to the model over the given transport.

        Args:
            model (Model): The model instance to generate the response.
            max_tokens (int): The maximum number of tokens to generate in the response.
            messages (list[dict]): The list of messages representing the conversation history.
            tools (list[dict]): The list of tools available to the model.
        Returns:
            Response: The response generated by the model.
        """

        if model.name == "LLM":
            if DEBUG_FLAG:
                print(f"___WRAPPER: messages: {messages}")
                print(f"___WRAPPER: Sending messages[] len={len(messages)} and tools[] len={len(tools)} to {model.name}")
            self.last_response = model.generate_response(max_tokens=max_tokens, messages=messages, tools=tools)
        elif model.name == "claude-opus-5":
            # do something
            pass
        elif model.name == "GPT":
            # etc
            pass
        else:
            raise ValueError(f"Unsupported model name: {model.name}")
        
        return self.last_response

    def get_response(self):
        """
        Returns the last response generated by the model along the given transport.

        Returns:
            str: The last response from the model.
        """
        return getattr(self, "last_response", None)
